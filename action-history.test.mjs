import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const url=name=>'data:text/javascript;base64,'+Buffer.from(readFileSync(new URL(name,import.meta.url),'utf8')).toString('base64');
const {createAction,pushAction,reverseAction,shouldUndoApp,UNDO_LIMIT}=await import(url('./action-history.js'));
const {moveBranchTo,toggleCompletion,removePreservingChildren,normalizeCompletion}=await import(url('./outline.js'));
const task=(id,depth=0)=>({id,depth,text:id,done:false});
const tasks=[task('parent'),task('child',1),task('other')];
const completed=toggleCompletion(tasks,'parent');
const completeAction=createAction({tasks},{tasks:completed},'Completion');
const typed=completed.map(t=>t.id==='child'?{...t,text:'Typed after completion'}:t);
assert.deepEqual(reverseAction({tasks:typed},completeAction).tasks,tasks.map(t=>t.id==='child'?{...t,text:'Typed after completion'}:t),'Completion undo preserves subsequent native text edits');
const moved=moveBranchTo(tasks,'child','other','child');
const moveAction=createAction({tasks},{tasks:moved},'Move','parent');
const editedMove=moved.map(t=>({...t,text:t.text+' edited'}));
assert.deepEqual(reverseAction({tasks:editedMove},moveAction).tasks,tasks.map(t=>({...t,text:t.text+' edited'})),'Reorder and depth undo preserve text edits');
assert.equal(moveAction.scopeId,'parent','Task actions retain the scope from before an automatic navigation');
const removedParent=removePreservingChildren(tasks,['parent']);
const deleteAction=createAction({tasks},{tasks:removedParent},'Delete');
const editedChild=removedParent.map(t=>t.id==='child'?{...t,text:'Surviving child edited'}:t);
assert.deepEqual(reverseAction({tasks:editedChild},deleteAction).tasks,tasks.map(t=>t.id==='child'?{...t,text:'Surviving child edited'}:t),'Undo restores a parent and nesting without reverting surviving child text');
const branch=tasks.map(t=>t.id==='parent'?{...t,collapsed:true}:t);
assert.deepEqual(reverseAction({tasks:[tasks[2]]},createAction({tasks:branch},{tasks:[tasks[2]]})).tasks,branch,'Branch deletion restores collapsed descendants');
assert.deepEqual(reverseAction({tasks:[]},createAction({tasks:completed},{tasks:[]})).tasks,completed,'Remove all is reversible');
const cleared=removePreservingChildren(completed,completed.filter(t=>t.done).map(t=>t.id));
assert.deepEqual(normalizeCompletion(reverseAction({tasks:cleared},createAction({tasks:completed},{tasks:cleared})).tasks),completed,'Clear completed restores the entire completed branch');
const inserted=[task('new'),...tasks];
assert.deepEqual(reverseAction({tasks:inserted.map(t=>({...t,text:'edited '+t.text}))},createAction({tasks},{tasks:inserted})).tasks,tasks.map(t=>({...t,text:'edited '+t.text})),'Undo insertion removes the added note and preserves older note text');
const fold=tasks.map(t=>t.id==='parent'?{...t,collapsed:true}:t);
assert.deepEqual(reverseAction({tasks:fold},createAction({tasks},{tasks:fold})).tasks,tasks,'Undo folding removes newly introduced optional fields');
const setting=createAction({theme:'dark'},{theme:'light'});
assert.deepEqual(reverseAction({theme:'light',font:'Poppins'},setting),{theme:'dark',font:'Poppins'},'Settings undo touches only committed setting fields');
assert.deepEqual(reverseAction({scopeId:'child',theme:'light'},createAction({scopeId:'parent'},{scopeId:'child'})),{scopeId:'parent',theme:'light'},'Navigation undo restores only the route');
const navigation=createAction({scopeId:null,tasks:fold},{scopeId:'parent',tasks},'Navigate');
assert.deepEqual(reverseAction({scopeId:'parent',tasks},navigation),{scopeId:null,tasks:fold},'Navigation with automatic unfolding undoes as one action');
assert.equal(createAction({tasks},{tasks:tasks.map(t=>({...t}))}),null,'No-op changes do not consume history');
assert.equal(pushAction([],null).length,0);
let state={tasks,theme:'dark',scopeId:null},history=[];
const apply=(patch,label)=>{const before=state;state={...state,...patch};history=pushAction(history,createAction(before,state,label))};
apply({tasks:[task('new'),...tasks]},'Insert');const oldestRetainedState=state;
apply({tasks:toggleCompletion(state.tasks,'parent')},'Completion');
apply({tasks:moveBranchTo(state.tasks,'new','other','child')},'Move');
apply({theme:'light'},'Theme');
apply({scopeId:'other'},'Navigate');
apply({tasks:[]},'Remove all');
assert.equal(history.length,UNDO_LIMIT,'Mixed action types share a single five-action limit');
for(let i=0;i<UNDO_LIMIT;i++)state=reverseAction(state,history.pop());
assert.deepEqual(state,oldestRetainedState,'Five undos restore newest-first; the sixth-oldest action is discarded');
assert.equal(history.length,0,'Undo does not insert new history entries');
const key={key:'z',ctrlKey:true,target:{closest:()=>null}};
assert.equal(shouldUndoApp(key),true,'Outside textboxes Ctrl+Z uses app undo');
assert.equal(shouldUndoApp({...key,ctrlKey:false,metaKey:true}),true,'Cmd+Z also uses app undo');
for(const field of ['defaultPrevented','isComposing','shiftKey','altKey'])assert.equal(shouldUndoApp({...key,[field]:true}),false);
assert.equal(shouldUndoApp({...key,target:{closest:selector=>selector.includes('textarea')?{}:null}}),false,'Textarea Ctrl+Z stays native even with app history');
assert.equal(shouldUndoApp({...key,target:{closest:selector=>selector.includes('input[type="search"]')?{}:null}}),false,'Search inputs use native undo');
assert.equal(shouldUndoApp({...key,target:{closest:selector=>selector.includes('[contenteditable]')?{}:null}}),false,'Editable content uses native undo');
assert.equal(shouldUndoApp({...key,key:'y'}),false);
console.log('Action history checks passed: five-action limit, mixed actions, native undo routing, surviving text edits, deletion, completion, movement, settings, and navigation.');
